function inside([x, y], poly) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

export const MAP = { width: 1000, latTop: 78, latBottom: -56 };
MAP.height = Math.round((MAP.width * (MAP.latTop - MAP.latBottom)) / 360);

export function project([lon, lat]) {
  return [((lon + 180) / 360) * MAP.width, ((MAP.latTop - lat) / 360) * MAP.width];
}

/** Builds the dot grid once: [{x, y, region}] */
export function buildDots(step = 2.6) {
  const dots = [];
  for (let lat = MAP.latTop - step / 2; lat > MAP.latBottom; lat -= step) {
    for (let lon = -180 + step / 2; lon < 180; lon += step) {
      for (const s of shapes) {
        if (inside([lon, lat], s.poly)) {
          const [x, y] = project([lon, lat]);
          dots.push({ x, y, lon, lat, region: s.region ? s.region(lon, lat) : null });
          break;
        }
      }
    }
  }
  return dots;
}
